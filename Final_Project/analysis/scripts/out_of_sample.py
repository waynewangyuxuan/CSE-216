"""Step 1 report: frozen v1.2 applied out of sample (coverage, category x strength, rules, UNSETTLED range,
coder-A-only vs coder-B-only categories), compared with Bet 5's in-sample 79/100.
Writes results/out_of_sample.md and results/out_of_sample.json."""
import itertools, os
from collections import Counter
from common import (CATS, IN, SL, SHORT, EDITOR_ONLY_RULES, FP, RES, load_windows, md_table, pct,
                    read_csv, write_json, write_text, frozen_rules)

STR_ORDER = ["strong", "moderate", "weak", "-"]


def groups(ws):
    g = {
        "NIRVANA, new in Bet 6 (out of sample)": [w for w in ws if w["nirvana_source"] == "bet6"],
        "NIRVANA, Bet 4 windows recoded with full history": [w for w in ws if w["nirvana_source"] == "bet6_fullview_recode"],
        "NIRVANA, Bet 4 labels kept (in calibration)": [w for w in ws if w["nirvana_source"] == "bet4"],
        "WildChat, Bet 7 (out of sample)": [w for w in ws if w["dataset"] == "WildChat"],
        "WildChat, Bet 4 sample (in calibration; incomplete sessions)": [w for w in ws if w["dataset"] == "WildChat-Bet4"],
    }
    g["**Out of sample: Bet 6 new + Bet 7**"] = g["NIRVANA, new in Bet 6 (out of sample)"] + g["WildChat, Bet 7 (out of sample)"]
    g["All 528"] = ws
    return g


def kappa(a, b):
    n = len(a)
    po = sum(x == y for x, y in zip(a, b)) / n
    ca, cb = Counter(a), Counter(b)
    pe = sum(ca[k] * cb[k] for k in set(a) | set(b)) / n / n
    return round((po - pe) / (1 - pe), 3) if pe < 1 else 1.0


def unsettled_range(ws, ar):
    """For each window with an UNSETTLED field, the categories it could get over every v1.1 value of those fields."""
    labels = {r["window_id"]: r for r in read_csv(os.path.join(RES, "inputs", "labels_final.csv"))}
    out = []
    for w in ws:
        if not w["unsettled_fields"]:
            continue
        fields = w["unsettled_fields"].split(";")
        base = labels[w["window_id"]]
        cats = Counter()
        for combo in itertools.product(*[sorted(ar.KNOWN[f]) for f in fields]):
            r = dict(base)
            r.update(dict(zip(fields, combo)))
            _, cat, strength, bad = ar.classify(r)
            if not bad:  # skip values v1.1 s2 forbids with this coverage
                cats[cat] += 1
        out.append({"window_id": w["window_id"], "dataset": w["dataset"], "unsettled": w["unsettled_fields"],
                    "possible": ", ".join(f"{SHORT[c]} {k}" for c, k in sorted(cats.items(), key=lambda x: CATS.index(x[0])))})
    return out


def main():
    ws = load_windows("final")
    A = {w["window_id"]: w for w in load_windows("coderA")}
    B = {w["window_id"]: w for w in load_windows("coderB")}
    ar = frozen_rules()
    J, md = {}, ["# Frozen v1.2 applied out of sample\n",
                 "Generated by `scripts/out_of_sample.py`. Rules: `inference/scripts/apply_rules.py`, hash checked by "
                 "`scripts/check_frozen.py` before every run. UNSETTLED fields go to R00 `INDETERMINATE` (frozen behavior, "
                 "stated before the run); their possible range is in table 5. Bet 5 in-sample baseline: 79/100 not indeterminate "
                 "(NIRVANA 58/70, WildChat 21/30).\n"]

    # 1. Coverage by group.
    rows, J["coverage"] = [], {}
    for name, g in groups(ws).items():
        k = sum(w["category"] != IN for w in g)
        rows.append([name, len(g), k, pct(k, len(g))])
        J["coverage"][name.strip("*")] = {"n": len(g), "not_indeterminate": k}
    rows.append(["Bet 5 calibration (in sample, for comparison)", 100, 79, "79.0%"])
    md += ["\n## 1. Coverage: share not indeterminate\n", md_table(["Set", "Windows", "Not indeterminate", "Share"], rows)]

    # 2. Category x strength by dataset.
    sets = ["NIRVANA", "WildChat", "WildChat-Bet4"]
    cs = [(c, s) for c in CATS for s in STR_ORDER if any(w["category"] == c and w["strength"] == s for w in ws)]
    rows, J["category_strength"] = [], {}
    for c, s in cs:
        n = [sum(w["category"] == c and w["strength"] == s and w["dataset"] == d for w in ws) for d in sets]
        rows.append([f"{SHORT[c]} / {s}"] + n + [sum(n)])
        J["category_strength"][f"{c}/{s}"] = dict(zip(sets, n))
    md += ["\n## 2. Category × strength, by set\n", md_table(["Category / strength"] + sets + ["All"], rows)]

    # 3. Rules by dataset.
    rules = sorted({w["rule"] for w in ws} | set(EDITOR_ONLY_RULES))
    rows, J["rules"] = [], {}
    for r in rules:
        n = [sum(w["rule"] == r and w["dataset"] == d for w in ws) for d in sets]
        rows.append([r + (" (editor only)" if r in EDITOR_ONLY_RULES else "")] + n + [sum(n)])
        J["rules"][r] = dict(zip(sets, n))
    md += ["\n## 3. Rule that fired, by set\n", md_table(["Rule"] + sets + ["All"], rows)]
    sl = [w for w in ws if w["category"] == SL]
    J["sl_by_rule16"] = {d: [sum(w["rule"] == "R16" for w in sl if w["dataset"] == d), sum(w["dataset"] == d for w in sl)] for d in sets}
    md.append("\nShare of surrender-leaning windows that rest on R16 (request type only): " + "; ".join(
        f"{d} {a}/{b} ({pct(a, b)})" for d, (a, b) in J["sl_by_rule16"].items()) + ".\n")
    wc_ed = sum(w["rule"] in EDITOR_ONLY_RULES for w in ws if w["dataset"].startswith("WildChat"))
    assert wc_ed == 0, "an editor-only rule fired on WildChat"
    md.append("Editor-only rules fired on WildChat windows: 0 (asserted).\n")

    # 4. By coverage.
    rows = []
    for c in ["C0", "C1", "C2"]:
        g = [w for w in ws if w["coverage"] == c]
        k = sum(w["category"] != IN for w in g)
        rows.append([c, len(g), k, pct(k, len(g))])
    md += ["\n## 4. By coverage code\n", md_table(["Coverage", "Windows", "Not indeterminate", "Share"], rows)]

    # 5. UNSETTLED range.
    ur = unsettled_range(ws, ar)
    J["unsettled_range"] = ur
    md += [f"\n## 5. Windows with an UNSETTLED field ({len(ur)}), all sent to R00\n",
           "Possible categories counted over every v1.1 value of the unsettled field(s), skipping combinations v1.1 forbids.\n\n",
           md_table(["Window", "Set", "Unsettled", "Possible categories (count of values)"],
                    [[u["window_id"], u["dataset"], u["unsettled"], u["possible"]] for u in ur])]

    # 6. Calibration windows: same category as Bet 5?
    cal = {r["window_id"]: r for r in read_csv(os.path.join(FP, "inference", "calibration", "final", "window_categories.csv"))}
    same = [w for w in ws if w["window_id"] in cal]
    changed = [(w["window_id"], cal[w["window_id"]]["category"], w["category"], w["nirvana_source"] or w["dataset"]) for w in same
               if cal[w["window_id"]]["category"] != w["category"]]
    J["calibration_changed"] = changed
    md += [f"\n## 6. The 100 calibration windows now\n",
           f"{len(same)} of Bet 5's 100 windows are in this run. {len(changed)} have a different category, all from Bet 6's full-history recode "
           "(the rules are identical, so a change means a label changed):\n\n",
           md_table(["Window", "Bet 5", "Now", "Label source"], [[a, SHORT[b], SHORT[c], d] for a, b, c, d in changed]) if changed else ""]

    # 7. Coder A only vs coder B only.
    rows, J["coder_ab"] = [], {}
    for d in sets + ["All"]:
        ids = [w["window_id"] for w in ws if d == "All" or w["dataset"] == d]
        a, b, f = [A[i]["category"] for i in ids], [B[i]["category"] for i in ids], [{w["window_id"]: w for w in ws}[i]["category"] for i in ids]
        agree = sum(x == y for x, y in zip(a, b))
        J["coder_ab"][d] = {"n": len(ids), "agree": agree, "kappa": kappa(a, b),
                            "final_eq_A": sum(x == y for x, y in zip(f, a)), "final_eq_B": sum(x == y for x, y in zip(f, b)),
                            "SL_A": a.count(SL), "SL_B": b.count(SL), "SL_final": f.count(SL)}
        j = J["coder_ab"][d]
        rows.append([d, len(ids), f"{agree} ({pct(agree, len(ids))})", j["kappa"], j["final_eq_A"], j["final_eq_B"], j["SL_A"], j["SL_B"], j["SL_final"]])
    md += ["\n## 7. Categories from each coder's labels alone\n",
           "Rules applied to coder A's labels only and to coder B's only (A = Opus, the adjudicator's own model; B = Sonnet). "
           "If adjudication lean toward A moved categories, final would track A much more than B.\n\n",
           md_table(["Set", "Windows", "A = B category", "κ", "Final = A", "Final = B", "SL under A", "SL under B", "SL final"], rows)]

    # 8. Known scope gap from Bet 5: U8 with V other than V0.
    u8 = [w["window_id"] for w in ws if w["U"] == "U8" and w["V"] not in {"V0", "?"} and not w["unrecognized_fields"]]
    J["u8_with_v_not_v0"] = u8
    md.append(f"\n## 8. Known scope: `U8` with `V` other than `V0` (not caught by R00)\n\n{len(u8)} windows: {', '.join(u8) or 'none'}.\n")

    # 9. What falls through to R99 (input for a future v1.3; the frozen rules are not changed).
    r99 = Counter(f"{w['D']} {w['F']} {w['U']}" for w in ws if w["rule"] == "R99")
    J["r99_combos"] = dict(r99.most_common())
    md += [f"\n## 9. Code combinations that reach R99 ({sum(r99.values())} windows)\n\n",
           md_table(["Decision function uptake", "Windows"], r99.most_common())]

    write_text(os.path.join(RES, "out_of_sample.md"), "".join(md))
    write_json(os.path.join(RES, "out_of_sample.json"), J)


if __name__ == "__main__":
    main()
