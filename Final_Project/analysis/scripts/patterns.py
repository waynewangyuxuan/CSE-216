"""Step 3: recurring behavior signatures (from v1.1 codes) and session types, across whole sessions.
Signatures are defined on codes before counting; each lists the categories its windows got, so a reader
sees whether a pattern maps to one category or straddles several. Writes results/patterns/*.csv and
results/patterns.md."""
import os
from collections import Counter
from common import CATS, SL, IN, NE, SUPPORT, SHORT, RES, load_windows, sessions, md_table, pct, write_csv, write_text

# (name, test on a window, why it is worth naming). Fixed before counting.
SIGNATURES = [
    ("Surface-only iteration (D2 V1 U4)", lambda w: w["D"] == "D2" and w["V"] == "V1" and w["U"] == "U4",
     "AI substance kept while only length, tone or format is asked for"),
    ("Whole paste (D4 V0 U1)", lambda w: w["D"] == "D4" and w["V"] == "V0" and w["U"] == "U1",
     "AI text pasted into the editor unchanged, no check seen"),
    ("Partial take (D3)", lambda w: w["D"] == "D3", "Writer selects or revises part of the AI content"),
    ("Ask, then write own text (D2 U7)", lambda w: w["D"] == "D2" and w["U"] == "U7",
     "AI proposes; the writer then types new text with no verbatim AI run"),
    ("Asked and moved on (U8)", lambda w: w["U"] == "U8", "Next action ignores the output"),
    ("Writer's text handed over for language (D1 F5)", lambda w: w["D"] == "D1" and w["F"] == "F5",
     "Writer supplies content, AI rewrites the wording"),
    ("Draft requested, kept in chat (D2 F4 U4/U5)", lambda w: w["D"] == "D2" and w["F"] == "F4" and w["U"] in ("U4", "U5"),
     "Generation asked for, then iterated or accepted in chat only"),
    ("Reasoned check (V3/V4)", lambda w: w["V"] in ("V3", "V4"), "Challenge with reasons, or comparison with a source"),
    ("AI checks itself (V2)", lambda w: w["V"] == "V2", "Writer asks the AI to verify its own output"),
]


def session_type(ws):
    """Fixed, simple types from category make-up (IND and NEU ignored)."""
    s = [w["category"] for w in ws]
    sl, sup = s.count(SL), sum(c in SUPPORT for c in s)
    if sl == 0 and sup == 0:
        return "No substantive category"
    if sl == 0:
        return "Support only"
    if sup == 0:
        return "Surrender-leaning only"
    return "Mixed: surrender-leaning and support"


def main():
    ws = load_windows("final")
    S = sessions(ws)
    whole = [w for v in S.values() for w in v]
    sig_rows = []
    md = ["# Patterns across sessions\n\nGenerated by `scripts/patterns.py`. Whole sessions only (NIRVANA 71, WildChat 35). "
          "Signatures were fixed on codes before counting. Narratives are written by hand in `../report/` from these ids.\n",
          "\n## 1. Behavior signatures\n\n"]
    for name, test, why in SIGNATURES:
        hit = [w for w in whole if test(w)]
        cats = Counter(w["category"] for w in hit)
        sess = {(w["dataset"], w["session_id"]) for w in hit}
        sig_rows.append({
            "signature": name, "meaning": why,
            "windows_NIRVANA": sum(w["dataset"] == "NIRVANA" for w in hit),
            "windows_WildChat": sum(w["dataset"] == "WildChat" for w in hit),
            "sessions": len(sess),
            "categories": "; ".join(f"{SHORT[c]} {cats[c]}" for c in CATS if cats[c]),
            "rules": "; ".join(f"{r} {k}" for r, k in sorted(Counter(w["rule"] for w in hit).items())),
            "example_windows": " ".join(w["window_id"] for w in hit[:4]),
        })
    write_csv(os.path.join(RES, "patterns", "signatures.csv"), sig_rows)
    md.append(md_table(["Signature", "NIRVANA", "WildChat", "Sessions", "Categories it got", "Rules"],
                       [[r["signature"], r["windows_NIRVANA"], r["windows_WildChat"], r["sessions"], r["categories"], r["rules"]]
                        for r in sig_rows]))

    # Session types.
    types = ["Surrender-leaning only", "Mixed: surrender-leaning and support", "Support only", "No substantive category"]
    trow = []
    for (d, sid), v in S.items():
        trow.append({"dataset": d, "session_id": sid, "type": session_type(v), "n_windows": len(v),
                     "sequence": " ".join(SHORT[w["category"]] for w in v)})
    write_csv(os.path.join(RES, "patterns", "session_types.csv"), trow)
    rows = []
    for t in types:
        n = [sum(r["type"] == t and r["dataset"] == d for r in trow) for d in ("NIRVANA", "WildChat")]
        lens = [r["n_windows"] for r in trow if r["type"] == t]
        rows.append([t] + n + [sum(n), pct(sum(n), len(trow)), f"{sum(lens) / len(lens):.1f}" if lens else "–"])
    md += ["\n## 2. Session types by category make-up (IND, NEU ignored)\n\n",
           md_table(["Type", "NIRVANA", "WildChat", "All", "Share", "Mean windows per session"], rows)]

    # Mixed sessions: what does the turn into and out of surrender look like in codes?
    into, outof = Counter(), Counter()
    for v in S.values():
        k = [w for w in v if w["category"] not in (IN, NE)]
        for a, b in zip(k, k[1:]):
            if a["category"] in SUPPORT and b["category"] == SL:
                into[f"{a['D']}/{a['F']} -> {b['D']}/{b['F']}"] += 1
            if a["category"] == SL and b["category"] in SUPPORT:
                outof[f"{a['D']}/{a['F']} -> {b['D']}/{b['F']}"] += 1
    md += ["\n## 3. Code pairs at switches (IND, NEU removed; decision/function of the two windows)\n\n",
           "Support → surrender-leaning, top 8:\n\n",
           md_table(["Pair", "Count"], into.most_common(8)),
           "\nSurrender-leaning → support, top 8:\n\n",
           md_table(["Pair", "Count"], outof.most_common(8))]

    # Narrative candidates: sessions named for each pattern (ids only).
    esc = [f"{d}:{sid}" for (d, sid), v in S.items()
           if any(w["D"] == "D1" for w in v) and any(w["D"] == "D4" for w in v[next(i for i, w in enumerate(v) if w["D"] == "D1") + 1:])]
    md += ["\n## 4. Narrative candidates (ids only)\n\n",
           f"- Escalation, a `D1` window later followed by `D4`: {', '.join(esc)}.\n"]
    for r in sig_rows[:5]:
        md.append(f"- {r['signature']}: first windows {r['example_windows']}.\n")
    write_text(os.path.join(RES, "patterns.md"), "".join(md))


if __name__ == "__main__":
    main()
