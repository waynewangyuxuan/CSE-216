"""Step 4 support: rerun the headline window and session measures under variants a skeptic would raise.
Variants change inputs or treat rules as missing; they never edit the frozen rules.
Writes results/sensitivity.md and results/sensitivity.json."""
import os
from common import SL, IN, SUPPORT, RES, load_windows, sessions, md_table, pct, write_json, write_text
from sessions import analyse


def recat(ws, test):
    out = []
    for w in ws:
        w = dict(w)
        if test(w):
            w["category"], w["strength"] = IN, "-"
        out.append(w)
    return out


def headline(ws, keep=lambda w: True):
    win = [w for w in ws if w["dataset"] in ("NIRVANA", "WildChat") and keep(w)]
    S = sessions(ws, keep=keep)
    J, _, rows = analyse(S, "")
    p = J["perm_test_excl_ind"]["SL->SL"]
    return {
        "windows": len(win),
        "not_ind": sum(w["category"] != IN for w in win),
        "sl_windows": sum(w["category"] == SL for w in win),
        "support_windows": sum(w["category"] in SUPPORT for w in win),
        "sessions": J["n_sessions"], "sessions_with_sl": J["sessions_with_sl"],
        "sl_sl_obs": p["observed"], "sl_sl_exp": p["expected"], "sl_sl_p": p["p_ge"],
        "leaves_to_support": J["leaves_sl_to_support"], "sl_with_later": J["sl_sessions_with_later_window"],
        "ends_in_sl": J["ends_in_sl"], "support_first": J["support_first"], "sl_first": J["sl_first"],
        "escalation": J["escalation_d1_to_d4"],
        "drift_sl_not_r16_p_later": J["drift"].get("SL not R16", {}).get("p_later", ""),
    }


def main():
    base = load_windows("final")
    variants = [
        ("Base (final labels, frozen v1.2)", base, lambda w: True),
        ("R16 treated as INDETERMINATE (no request-type-only surrender)", recat(base, lambda w: w["rule"] == "R16"), lambda w: True),
        ("All weak categories treated as INDETERMINATE", recat(base, lambda w: w["strength"] == "weak"), lambda w: True),
        ("Windows with an UNSETTLED field dropped", base, lambda w: not w["unsettled_fields"]),
        ("Coder A's labels only (Opus)", load_windows("coderA"), lambda w: True),
        ("Coder B's labels only (Sonnet)", load_windows("coderB"), lambda w: True),
        ("WildChat truncated conversations dropped (3)", base, lambda w: w["truncated_session"] == "0"),
        ("WildChat auditor-rejected conversations dropped (3)", base, lambda w: w["auditor_reject"] == "0"),
        ("NIRVANA windows with Bet 4 labels (3-turn views) dropped", base, lambda w: w["nirvana_source"] != "bet4"),
        ("NIRVANA only", base, lambda w: w["dataset"] == "NIRVANA"),
        ("WildChat only", base, lambda w: w["dataset"] == "WildChat"),
    ]
    J, rows = {}, []
    for name, ws, keep in variants:
        h = headline(ws, keep)
        J[name] = h
        rows.append([name, h["windows"], pct(h["not_ind"], h["windows"]), pct(h["sl_windows"], h["windows"]),
                     pct(h["support_windows"], h["windows"]), f"{h['sessions_with_sl']}/{h['sessions']}",
                     f"{h['sl_sl_obs']} vs {h['sl_sl_exp']} (p {h['sl_sl_p']})",
                     f"{h['leaves_to_support']}/{h['sl_with_later']}", h["ends_in_sl"],
                     f"{h['support_first']} / {h['sl_first']}", h["escalation"], h["drift_sl_not_r16_p_later"]])
    md = ["# Sensitivity of the headline measures\n\nGenerated by `scripts/sensitivity.py`. Whole sessions only "
          "(NIRVANA + WildChat Bet 7). Dropping a window removes it from its session's sequence, so neighbours become adjacent. "
          "\"Treated as INDETERMINATE\" keeps the window but removes its category; the frozen rules are not edited.\n\n",
          md_table(["Variant", "Windows", "Not IND", "SL share", "Support share", "Sessions with SL",
                    "SL→SL observed vs shuffled (IND removed)", "SL sessions later reaching support", "End in SL",
                    "Support first / SL first", "D1→D4 sessions", "Non-R16 SL later than shuffle, p"], rows)]
    write_text(os.path.join(RES, "sensitivity.md"), "".join(md))
    write_json(os.path.join(RES, "sensitivity.json"), {"order": [v[0] for v in variants], "variants": J})


if __name__ == "__main__":
    main()
